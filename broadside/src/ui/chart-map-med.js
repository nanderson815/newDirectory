// Longitude to x through a few knots (degrees east, map x), latitude to y at 46.7 units a degree.
const KX = [[-10.5, 0], [-5.5, 165], [22, 1000], [29.3, 1300]];
const lonX = (lon) => {
  for (let i = 1; i < KX.length; i++) {
    const [a, xa] = KX[i - 1], [b, xb] = KX[i];
    if (lon <= b || i === KX.length - 1) return xa + ((lon - a) * (xb - xa)) / (b - a);
  }
  return 0;
};
export const lonLat = (lon, lat) => [Math.round(lonX(lon) * 10) / 10, Math.round((45.6 - lat) * 467) / 10];

